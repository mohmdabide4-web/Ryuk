module.exports = {
  // الكلمات اللي لو الأدمن كتب وحدة منها بالخاص، يبدأ تقديم هذي الفعالية
  triggers: ["تقديم علم", "تقديم الاعلام", "تقديم الأعلام"],

  // اسم الفعالية يظهر بالرسالة النهائية
  eventTitle: "فعالية الاعلام",

  // القيم الثابتة لهذي الفعالية
  fixedValues: {
    الصنف: "C",
    المقدم: "ريوك",
  },

  // دالة بناء شكل الرسالة النهائية اللي ترسل بالجروب لعلم معيّن
  buildMessage(flagEmoji) {
    return (
      `*${this.eventTitle}\n` +
      `*𖣔━ ═━━❮⛄❯━━═ ━𖣔*\n` +
      `العلم〘${flagEmoji}〙*\n` +
      `                             *الصنف ⟬${this.fixedValues["الصنف"]}⟭*\n` +
      `*المقدم ⟬${this.fixedValues["المقدم"]} ⟭*\n` +
      `*𖣔━ ═━━❮⛄❯━━═ ━𖣔*`
    );
  },
};
